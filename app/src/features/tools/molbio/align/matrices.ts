/** Reads a matrix in NCBI layout: # comments, a header row of letters, then one row per letter. */
export function readMatrix(text: string): Matrix {
  const rows = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== '' && !line.startsWith('#'));
  const header = rows[0]?.split(/\s+/) ?? [];
  if (header.length === 0 || rows.length < 2) return fail('align.e.matrixEmpty');
  const table = new Map<string, number>();
  for (const row of rows.slice(1)) {
    const [letter, ...cells] = row.split(/\s+/);
    if (!letter || cells.length !== header.length) return fail('align.e.matrixRow', { row: letter ?? '' });
    cells.forEach((cell, i) => {
      const value = Number(cell);
      if (!Number.isFinite(value)) fail('align.e.matrixCell', { row: letter, cell });
      table.set(`${letter.toUpperCase()}${header[i]!.toUpperCase()}`, value);
    });
  }
  const letters = header.map((h) => h.toUpperCase());
  return { letters, score: (a, b) => table.get(`${a}${b}`) };
}

