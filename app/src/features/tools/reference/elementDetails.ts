const num = (text: string): number | null => (text === '-' ? null : Number(text));

const DETAILS: ReadonlyMap<number, ElementDetails> = new Map(
  ROWS.split('\n').map((row) => {
    const [number, density, melting, boiling, electronegativity, oxidation, isotopes] = row.split('|');
    const details: ElementDetails = {
      density: num(density),
      melting: num(melting),
      boiling: num(boiling),
      electronegativity: num(electronegativity),
      oxidation: oxidation === '-' ? '' : oxidation,
      isotopes,
    };
    return [Number(number), details];
  }),
);

/** The detail facts for an element by atomic number. */
export function detailsOf(number: number): ElementDetails {
  return (
    DETAILS.get(number) ?? {
      density: null,
      melting: null,
      boiling: null,
      electronegativity: null,
      oxidation: '',
      isotopes: '',
    }
  );
}
