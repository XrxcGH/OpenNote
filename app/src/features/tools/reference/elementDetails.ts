// Physical facts about each element for the detail card: density, melting and boiling points, electronegativity,
// common oxidation states, and isotopes. These are widely published measured values, rounded, from public references
// such as the IUPAC Periodic Table of the Elements and NIST (see THIRD_PARTY_NOTICES.md). A "-" is a value that is not
// known or does not apply: noble gases have no Pauling electronegativity to speak of, and the heaviest elements have
// been made in too small a quantity to measure.

export interface ElementDetails {
  /** Grams per cubic centimeter: at 20 °C for solids and liquids, and at 0 °C and 1 atm for gases. Null if unknown. */
  density: number | null;
  /** Melting point in kelvin, or null if unknown or if the element sublimes. */
  melting: number | null;
  /** Boiling point in kelvin (the sublimation point for carbon and arsenic), or null if unknown. */
  boiling: number | null;
  /** Pauling electronegativity, or null if none is given. */
  electronegativity: number | null;
  /** Common oxidation states, such as "+2, +3". Empty if not established. */
  oxidation: string;
  /** Mass numbers of the stable or naturally occurring isotopes, or of the longest-lived one. */
  isotopes: string;
}

