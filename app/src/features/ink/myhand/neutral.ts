/** How fast the neutral hand writes, in x-heights a second, for the time each point carries. */
const SPEED = 6;

function toGlyph(paths: Path[]): GlyphSample {
  const minX = Math.min(...paths.flat().map(([x]) => x));
  const maxX = Math.max(...paths.flat().map(([x]) => x));
  let t = 0;
  const strokes = paths.map((path) => {
    const flat: number[] = [];
    path.forEach(([x, y], i) => {
      if (i > 0) t += (Math.hypot(x - path[i - 1][0], y - path[i - 1][1]) / SPEED) * 1000;
      flat.push(Math.round((x - minX) * 1000) / 1000, Math.round(-y * 1000) / 1000, 0.6, Math.round(t));
    });
    t += 120;
    return flat;
  });
  return { strokes, width: maxX - minX, source: 'pen' };
}

const cache = new Map<string, GlyphSample>();

/** The neutral hand's glyph for a character, or null when it has none (a space, or a character it can't draw). */
export function neutralGlyph(char: string): GlyphSample | null {
  const def = DEFS[char];
  if (!def) return null;
  let glyph = cache.get(char);
  if (!glyph) {
    glyph = toGlyph(def);
    cache.set(char, glyph);
  }
  return glyph;
}

/** Every character the neutral hand can draw. */
export const NEUTRAL_CHARS: readonly string[] = Object.keys(DEFS);
