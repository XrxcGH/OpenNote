// A clean, neutral hand for the characters a person never wrote. Each glyph is drawn from lines and arcs in x-height
// units with y up from the baseline (x-height 1, capitals 1.45), and turned into the same form as the person's own
// letters, so the writer treats both alike. Generated writing lists the characters that came from here, so the
// person can add their own.
import type { GlyphSample } from './style';

type Pt = readonly [number, number];
type Path = Pt[];

/** A polyline through x, y pairs. */
const L = (...xy: number[]): Path => {
  const out: Path = [];
  for (let i = 0; i + 1 < xy.length; i += 2) out.push([xy[i], xy[i + 1]]);
  return out;
};

/** An arc of an ellipse from angle a0 to a1 in degrees (0 points right, 90 up), either way round. */
const A = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number): Path => {
  const steps = Math.max(4, Math.ceil(Math.abs(a1 - a0) / 15));
  return Array.from({ length: steps + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)] as Pt;
  });
};

/** Pieces joined into one stroke. */
const P = (...parts: Path[]): Path => parts.flat();
const dot = (x: number, y: number): Path => L(x, y, x + 0.01, y + 0.03);
const shift = (path: Path, dx: number, dy = 0, sx = 1, sy = 1): Path =>
  path.map(([x, y]) => [x * sx + dx, y * sy + dy]);
const mirror = (paths: Path[], width: number): Path[] =>
  paths.map((path) => path.map(([x, y]) => [width - x, y] as Pt));

