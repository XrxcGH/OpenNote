// A program that tries each route past full Python's cut-off it knows. Then it looks for a JavaScript value, or a
// way to make one, in all Python sees. It runs without lockdown in python.test.ts and in the worker in python.test.tsx.
//
// The routes: the import hook's table, dropping the refusing finder, the original `_imp.create_builtin` from the
// wrapper's closure, and Pyodide's classes. The walk covers each object the garbage collector tracks, what it refers
// to, and its attributes. A JavaScript value found there is walked in turn to a depth of four: its properties, its
// prototypes, and theirs.

const lines = (...text: string[]) => text.join('\n') + '\n';

export const REACH = lines(
  'import sys, gc, _imp',
  'reached = []',
  'def is_js(value):',
  '    try:',
  '        return any(c.__name__ == "JsProxy" for c in type(value).__mro__)',
  '    except Exception:',
  '        return False',
  'def makes_js(value):',
  '    owner = getattr(value, "__self__", None)',
  '    return getattr(owner, "__name__", None) == "_pyodide_core" and callable(value)',
  'held = [f for f in sys.meta_path if getattr(f, "jsproxies", None)]',
  'print("import hook:", len(held))',
  'for f in held:',
  '    reached.extend(f.jsproxies.values())',
  'first = sys.meta_path.pop(0)',
  'try:',
  '    import js',
  '    reached.append(js)',
  '    print("import js: imported")',
  'except ImportError:',
  '    print("import js: refused")',
  'sys.meta_path.insert(0, first)',
  'makers = []',
  'create = _imp.create_builtin',
  'while getattr(create, "__closure__", None):',
  '    create = create.__closure__[0].cell_contents',
  'try:',
  '    from importlib.machinery import BuiltinImporter',
  '    core = create(BuiltinImporter.find_spec("_pyodide_core"))',
  '    makers.extend(name for name in ("to_js", "create_proxy", "create_once_callable") if hasattr(core, name))',
  'except Exception:',
  '    pass',
  'print("closure makers:", makers)',
  'def classes(base, out, ids):',
  '    for sub in type.__subclasses__(base):',
  '        if id(sub) not in ids:',
  '            ids.add(id(sub))',
  '            out.append(sub)',
  '            classes(sub, out, ids)',
  '    return out',
  'made = []',
  'for cls in classes(object, [], set()):',
  '    if not cls.__name__.startswith("Js"):',
  '        continue',
  '    for how in ("call", "new", "dunder"):',
  '        try:',
  '            if how == "call":',
  '                value = cls("A", "b")',
  '            elif how == "new":',
  '                value = cls.new("A", "b")',
  '            else:',
  '                value = cls.__new__(cls, "A", "b")',
  '            if is_js(value):',
  '                made.append(cls.__name__ + "." + how)',
  '                reached.append(value)',
  '        except BaseException:',
  '            pass',
  'print("classes make:", made)',
  'found = []',
  'for item in gc.get_objects():',
  '    values = [item] + list(gc.get_referents(item))',
  '    attrs = getattr(item, "__dict__", None)',
  '    if isinstance(attrs, dict):',
  '        values += list(attrs.values())',
  '    found.extend(v for v in values if is_js(v) or makes_js(v))',
  'reached.extend(v for v in found if is_js(v))',
  'makers.extend(getattr(v, "__name__", "?") for v in found if makes_js(v))',
  'print("makers:", sorted(set(makers)))',
  'names = {"fetch", "eval", "postMessage", "setTimeout", "setInterval", "clearTimeout", "importScripts"}',
  'names |= {"XMLHttpRequest", "WebSocket", "queueMicrotask", "MessageChannel", "Worker", "runPython", "FS"}',
  'powers = set()',
  'seen = set()',
  'def walk(value, depth):',
  '    if depth > 4 or id(value) in seen:',
  '        return',
  '    seen.add(id(value))',
  '    try:',
  '        keys = dir(value)',
  '    except Exception:',
  '        return',
  '    powers.update(k for k in keys if k in names)',
  '    for key in keys + ["constructor", "__proto__", "prototype"]:',
  '        try:',
  '            child = getattr(value, key)',
  '        except Exception:',
  '            continue',
  '        if is_js(child):',
  '            walk(child, depth + 1)',
  'ran = False',
  'for value in reached:',
  '    walk(value, 0)',
  '    try:',
  '        value.constructor.constructor("return 1")()',
  '        ran = True',
  '    except Exception:',
  '        pass',
  'print("reached:", len(reached))',
  'print("powers:", sorted(powers))',
  'print("code from text:", "ran" if ran else "refused")',
);

/** What REACH prints when the cut-off holds. */
export const REACH_HELD = lines(
  'import hook: 0',
  'import js: refused',
  'closure makers: []',
  'classes make: []',
  'makers: []',
  'reached: 0',
  'powers: []',
  'code from text: refused',
);
