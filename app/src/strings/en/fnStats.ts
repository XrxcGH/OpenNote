// Typed as unknown values on purpose, as fnMath is. Function text is looked up by function name at run time, never
// through t(), and a typed key for each of the 149 names makes the message key union too large for the compiler.
export const fnStats: Readonly<Record<string, unknown>> = Object.fromEntries(
  Object.entries(LINES).map(([name, [description, list]]) => [
    name,
    { description, params: Object.fromEntries(list.split(' ').map((p) => [p, arg[p] ?? ''])) } satisfies FnText,
  ]),
);
